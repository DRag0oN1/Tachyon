import { readFileSync } from 'node:fs';
import { test, expect } from '../../web/e2e-support';

test('@production-strategy trained policy and actual local CAD reference share one workspace', async ({ page, request, baseURL }) => {
  test.setTimeout(180_000);
  const file = process.env.TACHYON_E2E_SESSION_FILE;
  test.skip(!file, 'Requires a running owner-local app and its private session file.');
  expect(['127.0.0.1','localhost']).toContain(new URL(baseURL!).hostname);
  const token = readFileSync(file!,'utf8').trim();
  const headers = { 'X-Tachyon-Session':token, Origin:baseURL! };
  const original = await (await request.get('/api/workspace',{headers})).json();
  const catalog = await (await request.get('/api/catalog',{headers})).json();
  const reference = catalog.components.find((c:{id:string}) => c.id==='v5_motor_reference');
  expect(reference,'Exact genuine motor reference required; no substitute fixture').toBeTruthy();
  expect(reference.originKind).toBe('manufacturer_cad');
  expect(reference.referenceOnly).toBe(true);
  const mobile = test.info().project.name.includes('mobile');
  const theme = mobile ? 'shift' : 'snap';
  const errors:string[]=[]; const remote:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=> { if (/^https?:/.test(request.url()) && new URL(request.url()).origin!==baseURL) remote.push(new URL(request.url()).origin); });
  try {
    await request.patch('/api/workspace',{headers,data:{activeComponentId:reference.id,preferences:{theme,mode:'simple'}}});
    await page.addInitScript(owner=>sessionStorage.setItem('tachyon.owner-session',owner),token);
    await page.goto('/');
    await expect(page.getByRole('button',{name:'Generate Strategy',exact:true})).toBeEnabled({timeout:20_000});
    // Inspect the genuine source explicitly. Strategy must not leave unrelated
    // reference CAD behind its playbook or pretend it realizes the proposal.
    await page.getByRole('button',{name:'Components',exact:true}).click();
    await page.locator('.component-row').filter({hasText:reference.name}).click();
    const status=page.getByTestId('scene-status');
    await expect(status).toHaveAttribute('data-state','ready',{timeout:100_000});
    expect(Number(await status.getAttribute('data-mesh-count'))).toBeGreaterThan(1);
    await status.locator('summary').click();
    await expect(status).toContainText('IMPORTED REFERENCE');
    await status.locator('summary').click();
    await page.getByRole('button',{name:'Close Components',exact:true}).click();
    await page.screenshot({path:test.info().outputPath(`${test.info().project.name}-${theme}-authentic-source-private.png`)});
    await page.getByRole('button',{name:'Home',exact:true}).click();
    await page.getByRole('button',{name:'Generate Strategy',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Low quadrant scoring cycles',exact:true})).toBeVisible({timeout:35_000});
    await expect(page.locator('.strategy-domain')).toContainText('Abstract simulation only');
    await expect(status).toHaveCount(0);
    await page.locator('.playbook-analysis > summary').click();
    await expect(page.locator('.strategy-timeline li')).toHaveCount(59);
    await page.locator('.strategy-timeline button').filter({hasText:'Place an alliance Pin'}).first().click();
    await page.screenshot({path:test.info().outputPath(`${test.info().project.name}-${theme}-strategy-authentic-reference-private.png`)});
    await page.getByRole('button',{name:'Compare engineering alternatives',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Choose your machine.',exact:true})).toBeVisible();
    const choice=page.locator('.architecture-options button').first();
    if (await choice.count()) await choice.click();
    await page.getByRole('button',{name:'Assemble local recipe',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Assembly still required',exact:true})).toBeVisible({timeout:20_000});
    await expect(page.getByTestId('design-canvas')).toHaveCount(0);
    await expect(status).toHaveCount(0);
    await page.screenshot({path:test.info().outputPath(`${test.info().project.name}-${theme}-architecture-blockers-private.png`)});
    await page.getByRole('button',{name:'Expand assistant',exact:true}).click();
    await expect(page.getByTestId('ai-core')).toHaveAttribute('data-state','expanded');
    await page.getByLabel('Design request',{exact:true}).fill('Raise scoring height');
    await page.getByRole('button',{name:'Send request',exact:true}).click();
    await expect(page.locator('.assistant-reply')).toContainText(/qualified|unavailable|recipe|proposal/i);
    await expect(page.getByRole('button',{name:'Apply',exact:true})).toBeDisabled();
    await page.screenshot({path:test.info().outputPath(`${test.info().project.name}-${theme}-unsupported-height-private.png`)});
    await page.getByRole('button',{name:'Full-screen assistant',exact:true}).click();
    await expect(page.getByTestId('ai-core')).toHaveAttribute('data-state','fullscreen');
    await page.getByRole('button',{name:'Restore assistant panel',exact:true}).click();
    await page.getByRole('button',{name:'Close assistant',exact:true}).click();
    await expect(page.getByTestId('ai-core')).toHaveAttribute('data-state','compact');
    await page.getByRole('button',{name:'Strategy',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Low quadrant scoring cycles',exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    expect(errors).toEqual([]); expect(remote).toEqual([]);
    test.info().annotations.push({type:'boundary',description:'Actual frozen neural inference plus genuine source inspection. The reference is not a generated robot; missing architecture geometry and unsupported edits remain blocked.'});
  } finally { await request.patch('/api/workspace',{headers,data:original}).catch(()=>{}); }
});
