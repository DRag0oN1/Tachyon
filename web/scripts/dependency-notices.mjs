import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const rows = [];
const licenses = [];
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path) continue;
  const name = path.split('node_modules/').at(-1);
  const folder = join(root, path);
  const installed = existsSync(join(folder, 'package.json'));
  const pkg = installed ? JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8')) : {};
  // This release omits package.json's license field; its distributed LICENSE
  // and upstream README explicitly grant MIT (the full text is retained below).
  const license = entry.license ?? pkg.license ?? ({ 'webgl-constants': 'MIT' })[name];
  if (!license) throw new Error(`Missing license provenance: ${name}`);
  const scope = manifest.dependencies[name] ? 'Runtime' : manifest.devDependencies[name] ? 'Development' : 'Transitive';
  rows.push(`| ${name} | ${entry.version} | ${license} | ${scope} | [npm source](https://www.npmjs.com/package/${name}/v/${entry.version}) |`);
  if (installed) {
    const files = readdirSync(folder).filter(file => /^(licen[cs]e|copying|notice)([.-].*)?$/i.test(file));
    for (const file of files) {
      try {
        // Normalize aggregate formatting while retaining every license word.
        const text = readFileSync(join(folder, file), 'utf8').replace(/\r\n?/g, '\n').split('\n').map(line => line.trimEnd()).join('\n').trimEnd();
        licenses.push(`${name}@${entry.version} — ${file}\n${'='.repeat(72)}\n${text}\n`);
      }
      catch (error) { if (error.code !== 'EISDIR') throw error; }
    }
  }
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), `# Tachyon frontend dependency provenance\n\nGenerated by \`npm run licenses\` from the exact npm lockfile and installed packages.\nDependencies remain separate from all CAD source rights. No third-party CAD, fonts,\nicons, images or application source have been copied into the frontend. Original\nUI icons and assistant glyphs were authored for Tachyon.\n\nFull available installed copyright/license texts are retained in\n[public/THIRD_PARTY_NOTICES.txt](public/THIRD_PARTY_NOTICES.txt), which Vite also\nincludes in the built distribution. Uninstalled optional platform binaries appear\nin the lockfile provenance table but are not distributed. Registry tarball identity\nand integrity are recorded in \`package-lock.json\`.\n\nSHA-256 HTTP/LAN fallback uses the MIT-licensed [noble-hashes upstream API](https://github.com/paulmillr/noble-hashes#usage). React 19 and Fiber 9 compatibility follows the [official R3F documentation](https://r3f.docs.pmnd.rs/getting-started/introduction).\n\n| Package | Locked version | License | Use | Provenance |\n| --- | --- | --- | --- | --- |\n${rows.sort().join('\n')}\n`);
mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(join(root, 'public/THIRD_PARTY_NOTICES.txt'), `Tachyon frontend third-party copyright and license texts\nGenerated from installed, locked npm dependencies. These licenses grant no rights\nto user-provided CAD. No source CAD or converted meshes are bundled.\n\n${licenses.join('\n')}`.trimEnd() + '\n');
console.log(`Recorded ${rows.length} locked dependency entries and ${licenses.length} license/notice texts.`);
